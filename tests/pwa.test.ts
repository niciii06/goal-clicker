import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import test from 'node:test';
import { config } from '../proxy.ts';

test('the service worker never answers API, login or non GET requests from its cache', async () => {
  const sw = await readFile(new URL('../public/sw.js', import.meta.url), 'utf8');
  assert.match(sw, /if \(request\.method !== "GET"\) return;/);
  assert.match(sw, /url\.pathname\.startsWith\("\/api\/"\) \|\| url\.pathname\.startsWith\("\/auth\/"\)\) return;/);
  // Pages always come from the network; only the offline page is a fallback.
  assert.match(sw, /request\.mode === "navigate"\) event\.respondWith\(networkOrOffline\(request\)\)/);
});

test('app shell files and the API skip the proxy while pages still pass through it', () => {
  const matcher = new RegExp(`^${config.matcher[0]}$`);
  for (const path of ['/sw.js', '/manifest.webmanifest', '/offline.html', '/sounds/crowd-ooh.mp3', '/icons/icon-192.png']) assert.doesNotMatch(path, matcher, path);
  for (const path of ['/', '/kader', '/auth/signout', '/auth/callback']) assert.match(path, matcher, path);
  // API routes check sessions themselves; the proxy would only cost one more function run per poll.
  for (const path of ['/api/save', '/api/multiplayer', '/api/auth/get-session']) assert.doesNotMatch(path, matcher, path);
});

test('the favicon and every app icon source use the brand green, the old blue is gone', async () => {
  const [favicon, generator, sw] = await Promise.all(['../public/favicon.svg', '../scripts/pwa-icons.mjs', '../public/sw.js'].map((path) => readFile(new URL(path, import.meta.url), 'utf8')));
  assert.match(favicon, /<rect[^>]*fill="#0a7d43"/);
  assert.doesNotMatch(favicon, /#0071e3/);
  assert.match(generator, /fill="#0a7d43"/);
  assert.doesNotMatch(generator, /#0071e3/);
  // The home screen icon is generated by the same script, so the PNG files cannot drift apart from the favicon.
  assert.match(generator, /apple-touch-icon\.png/);
  // Installed copies drop the cached old icons: the cache version moved past v1.
  assert.doesNotMatch(sw, /const VERSION = "v1";/);
});

test('the manifest and layout reference the generated icon files', async () => {
  const [layout, manifest] = await Promise.all(['../app/layout.tsx', '../app/manifest.ts'].map((path) => readFile(new URL(path, import.meta.url), 'utf8')));
  for (const path of ['/favicon.svg', '/icons/icon-192.png', '/apple-touch-icon.png']) assert.ok(layout.includes(path), path);
  for (const path of ['/icons/icon-192.png', '/icons/icon-512.png', '/icons/icon-maskable-512.png']) assert.ok(manifest.includes(path), path);
});
