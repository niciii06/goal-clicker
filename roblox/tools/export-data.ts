mkdirSync(OUT, { recursive: true });

function lua(value: unknown, indent = ""): string {
  if (value === null || value === undefined) return "nil";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number") {
    if (!Number.isFinite(value)) return value > 0 ? "math.huge" : "-math.huge";
    return Number.isInteger(value) ? String(value) : String(Number(value.toPrecision(10)));
  }
  if (typeof value === "string") return JSON.stringify(value).replace(/\\u([0-9a-fA-F]{4})/g, (_, hex) => String.fromCodePoint(parseInt(hex, 16)));
  const next = indent + "\t";
  if (Array.isArray(value)) {
    if (!value.length) return "{}";
    const simple = value.every((item) => typeof item !== "object" || item === null);
    if (simple) return `{ ${value.map((item) => lua(item)).join(", ")} }`;
    return `{\n${value.map((item) => `${next}${lua(item, next)},`).join("\n")}\n${indent}}`;
  }
  const entries = Object.entries(value as Record<string, unknown>).filter(([, item]) => item !== undefined);
  if (!entries.length) return "{}";
  return `{\n${entries.map(([key, item]) => `${next}${/^[A-Za-z_][A-Za-z0-9_]*$/.test(key) ? key : `[${JSON.stringify(key)}]`} = ${lua(item, next)},`).join("\n")}\n${indent}}`;
}

function write(name: string, comment: string, value: unknown) {
  writeFileSync(join(OUT, `${name}.luau`), `--!strict\n-- ${comment}\n-- Generated by roblox/tools/export-data.ts from the web version. Do not edit by hand.\nreturn ${lua(value)}\n`);
}

const STAT_KEYS = ["finishing", "shortPassing", "dribbling", "standingTackle", "gkReflexes", "gkPositioning", "gkHandling", "reactions", "sprintSpeed", "stamina"] as const;
const scrapIds = new Set(SCRAP_PLAYERS.map((player) => player.id));

// Players are split into chunks so no single module becomes unwieldy in Studio.
const players = STAR_XI_PLAYERS.map((player) => {
  const stats = player.originalAttributes?.stats as Record<string, { value: number }> | undefined;
  const attributes: Record<string, number> = {};
  if (stats) for (const key of STAT_KEYS) if (Number.isFinite(stats[key]?.value)) attributes[key] = stats[key].value;
  const walkout = getWalkoutPresentation(player);
  return {
    id: player.id,
    name: player.name,
    position: player.position,
    positions: [...player.positions],
    rating: player.rating,
    price: player.price,
    accent: player.accent,
    countryCode: player.countryCode,
    isCustom: player.isCustom || undefined,
    benchOnly: player.benchOnly || undefined,
    symbol: player.symbol,
    cardType: player.cardType,
    packWeight: player.packWeight,
    scrap: scrapIds.has(player.id) || undefined,
    tier: getStarCardTier(player),
    attributes: Object.keys(attributes).length ? attributes : undefined,
    look: {
      country: walkout.country, skin: walkout.skin, hair: walkout.hair, hairColor: walkout.hairColor, beard: walkout.beard,
      height: walkout.height, build: walkout.build, celebration: walkout.celebration,
      kitPrimary: walkout.kitPrimary, kitSecondary: walkout.kitSecondary, boots: walkout.boots,
    },
  };
});
const CHUNK = 400;
const chunkNames: string[] = [];
for (let index = 0; index * CHUNK < players.length; index += 1) {
  const name = `Players${index + 1}`;
  chunkNames.push(name);
  write(name, `Card pool part ${index + 1}.`, players.slice(index * CHUNK, (index + 1) * CHUNK));
}
writeFileSync(join(OUT, "Players.luau"), `--!strict\n-- Complete card pool in the original order of STAR_XI_PLAYERS.\n-- Generated by roblox/tools/export-data.ts from the web version. Do not edit by hand.\nlocal all = {}\nfor _, part in { ${chunkNames.map((name) => `require(script.Parent.${name}) :: any`).join(", ")} } do\n\tfor _, player in part do\n\t\ttable.insert(all, player)\n\tend\nend\nreturn all\n`);

write("Catalog", "Formations, packs, tournaments, transfer cards, weights and missions.", {
  positions: [...STAR_POSITIONS],
  positionNames: STAR_POSITION_NAMES,
  formations: STAR_FORMATIONS.map((formation) => ({ id: formation.id, label: formation.label, slots: formation.slots.map((slot) => ({ position: slot.position, x: slot.x, y: slot.y })), unlockSeason: getFormationUnlockSeason(formation.id) })),
  starPacks: STAR_PACKS.map((pack) => ({ ...pack, odds: pack.odds.map((odds) => ({ ...odds })), unlockSeason: getPackUnlockSeason(pack.id) })),
  rewardPacks: REWARD_PACKS.map((pack) => ({ ...pack, odds: pack.odds.map((odds) => ({ ...odds })) })),
  scrapRatingGroups: SCRAP_RATING_GROUPS.map((group) => ({ ...group })),
  tournaments: TOURNAMENTS.map((tournament) => ({ ...tournament, opponents: tournament.opponents.map((opponent) => ({ ...opponent, scorers: [...opponent.scorers] })), unlockSeason: getTournamentUnlockSeason(tournament.id) })),
  transferPlayers: TRANSFER_PLAYERS,
  goalWeights: GOAL_POSITION_WEIGHTS,
  assistWeights: ASSIST_POSITION_WEIGHTS,
  faultWeights: DEFENSIVE_FAULT_WEIGHTS,
  missions: MISSION_TEMPLATES,
});

const UPGRADE_IDS = ["boots", "ballboy", "technique", "instinct", "coach", "striker", "academy", "floodlight", "longshot", "scout", "var", "freekick", "stadium", "worldclass", "broadcast", "sponsor", "ballondor", "superclub", "captain", "golden", "legacy"];
write("Progression", "Achievements, ranks, season milestones and unlock seasons.", {
  achievements: ACHIEVEMENTS,
  ranks: RANKS,
  seasonMilestones: SEASON_MILESTONES.map((milestone) => ({ ...milestone, rewards: [...milestone.rewards] })),
  upgradeUnlockSeasons: Object.fromEntries(UPGRADE_IDS.map((id) => [id, getUpgradeUnlockSeason(id)])),
  dailyRewardDays: DAILY_REWARD_DAYS,
  careerMilestones: CAREER_MILESTONES,
  legacyCareerMilestoneIds: LEGACY_CAREER_MILESTONES.map((milestone) => milestone.id),
  milestoneMetricLabels: MILESTONE_METRIC_LABELS,
});

write("Texts", "Press conference questions, news headlines and transfer clubs.", {
  pressQuestions: PRESS_QUESTIONS,
  gazetteChampion: [...GAZETTE_CHAMPION_HEADLINES],
  gazetteExit: [...GAZETTE_EXIT_HEADLINES],
  transferClubs: [...TRANSFER_INTERESTED_CLUBS],
});

// Travel: every reachable venue with its precomputed door to door plan. Route geometry is
// reduced to a few points per segment; it only feeds the small travel map in the UI.
function shrink(points: { lat: number; lon: number }[], maximum: number) {
  if (points.length <= maximum) return points.map((point) => ({ lat: +point.lat.toFixed(4), lon: +point.lon.toFixed(4) }));
  return Array.from({ length: maximum }, (_, index) => points[Math.round(index * (points.length - 1) / (maximum - 1))]).map((point) => ({ lat: +point.lat.toFixed(4), lon: +point.lon.toFixed(4) }));
}
const venues = new Map<string, Venue>();
const seasonClubs: unknown[][] = [];
for (let division = 1; division <= 15; division += 1) {
  const row: unknown[] = [];
  for (let index = 0; index < 5; index += 1) {
    const club = seasonGeography(division, index);
    venues.set(club.venue.id, club.venue);
    row.push({ id: club.id, name: club.name, venueId: club.venue.id });
  }
  seasonClubs.push(row);
}
const tournamentVenues: Record<string, string> = {};
for (const tournament of TOURNAMENTS) for (const opponent of tournament.opponents) {
  const venue = tournamentVenue(opponent.id);
  venues.set(venue.id, venue);
  tournamentVenues[opponent.id] = venue.id;
}
venues.set(VENUES.wembley.id, VENUES.wembley);
const venueTable: Record<string, unknown> = {};
for (const venue of venues.values()) {
  const plan = planJourney(venue);
  const normal = classifyDestination(venue);
  venueTable[venue.id] = {
    id: venue.id, stadium: venue.stadium, city: venue.city, country: venue.country, lat: venue.lat, lon: venue.lon,
    km: distanceKm(HOME_VENUE, venue), region: normal, eliteRegion: classifyDestination(venue, true),
    plan: {
      acceleration: plan.acceleration, realSeconds: plan.realSeconds,
      segments: plan.segments.map((segment) => ({ mode: segment.mode, label: segment.label, from: segment.from.name, to: segment.to.name, realSeconds: segment.realSeconds, distanceKm: segment.distanceKm, points: shrink(segment.points, 12) })),
    },
  };
}
write("Travel", "Home venue, all away venues with door to door plans, season clubs and league names.", {
  home: { id: HOME_VENUE.id, stadium: HOME_VENUE.stadium, city: HOME_VENUE.city, country: HOME_VENUE.country, lat: HOME_VENUE.lat, lon: HOME_VENUE.lon },
  venues: venueTable,
  seasonClubs,
  tournamentVenues,
  wembley: VENUES.wembley.id,
  leagueLabels: [...LEAGUE_LABELS],
  regionLabels: [...REGION_LABELS],
});

console.log(`Exported ${players.length} players, ${venues.size} venues into ${OUT}`);
